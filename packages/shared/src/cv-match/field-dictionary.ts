/**
 * Fields of work: the words that show a job belongs to a field. A requirement naming any of `names` asks for that
 * field; `also` lists wider wording that counts as doing it but does not by itself ask for it (a customs officer has
 * import-export experience, an import-export line does not ask for customs).
 */
export interface FieldEntry {
  names: string[];
  also?: string[];
  /** Names only read in a requirement: without tones they collide in a CV ("kho" with "khó", "dược" with "được"). */
  reqOnly?: string[];
  /** Only the job title proves it: "quản lý lịch họp" among the duties does not make a manager. */
  titleOnly?: boolean;
}

