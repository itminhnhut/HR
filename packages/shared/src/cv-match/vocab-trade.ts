/**
 * Professional vocabulary of common occupations. A `trade` term claimed only in a skills list counts when the work
 * history or education belongs to the same occupation (see FAMILY_SUPPORT), so copying the ad into a CV does not help
 * and a genuine skills section is not punished.
 */
import type { KeywordGroup } from './keyword-types.js';

function trade(id: string, label: string, family: string, terms: string[], covers?: string[]): KeywordGroup {
  return { id, label, kind: 'trade', family, terms, ...(covers ? { covers } : {}) };
}

function cert(id: string, label: string, terms: string[]): KeywordGroup {
  return { id, label, kind: 'cert', terms };
}

